// Synthetic local-runtime fixture only. Never deploy this test worker.
import { UploadLedger, UPLOAD_LIMITS as L } from "../../src/uploads.mjs";
import { UploadCleanup } from "../../src/upload-cleanup.mjs";

function check(value, reason) { if (!value) throw new Error(`Cleanup runtime assertion: ${reason}`); }
async function digest(bytes) {
  return [...new Uint8Array(await crypto.subtle.digest("SHA-256", bytes))]
    .map(byte => byte.toString(16).padStart(2, "0")).join("");
}

export class UploadCleanupProbe {
  constructor(state, env) { this.storage = state.storage; this.bucket = env.TEST_BUCKET; }
  async fetch() {
    let now = 1_800_000_000_000;
    const owner = crypto.randomUUID(), room = crypto.randomUUID();
    const options = { now: () => now, authorize: (actor, requestedRoom) => actor === owner && requestedRoom === room };
    let ledger = new UploadLedger(this.storage, options);
    const keys = [];
    for (const mode of ["partial", "lost-abort", "lost-delete", "failed-head", "lost-completion"]) {
      // Two real multipart parts. These generated bytes are deliberately not
      // audio; a completed object is rejected by profile verification below.
      const bytes = new Uint8Array(L.partBytes + 37);
      bytes[0] = 17; bytes[bytes.length - 1] = 42;
      const input = { id: crypto.randomUUID(), room_id: room, occurrence_id: crypto.randomUUID(),
        size: bytes.length, sha256: await digest(bytes), profile: "mp3-44100-stereo", explicit_selection: true };
      await ledger.admit(owner, input);
      const plan = await ledger.beginCreate(owner, input.id, 1);
      const upload = await this.bucket.createMultipartUpload(plan.key, { httpMetadata: { contentType: plan.contentType } });
      await ledger.settleCreate(input.id, 1, upload.uploadId)
        .catch(error => { throw new Error(`Creation settlement: ${error.code}`); });
      keys.push(plan.key);
      for (const number of [1, 2]) {
        const lease = await ledger.leasePart(owner, input.id, 1, number);
        const part = await upload.uploadPart(number, bytes.subarray(lease.offset, lease.offset + lease.size));
        await ledger.recordPart(input.id, 1, { number, lease_id: lease.lease_id, size: lease.size, etag: part.etag })
          .catch(error => { throw new Error(`Part settlement: ${error.code}`); });
      }
      if (mode === "lost-completion") {
        const completion = await ledger.beginComplete(owner, input.id, 1);
        await upload.complete(completion.parts.map(part => ({ partNumber: part.number, etag: part.etag })));
        // Simulate a completion reply lost before its ledger settlement.
        await ledger.cancel(owner, input.id, 1);
        check((await new UploadCleanup(ledger, this.bucket).run()).attempted === 0, "uncertain completion was withheld");
        const stored = await this.bucket.get(plan.key);
        check(stored !== null, "completed object exists during uncertainty");
        const storedBytes = await stored.arrayBuffer();
        check(storedBytes.byteLength === bytes.length && await digest(storedBytes) === input.sha256, "stored bytes match");
        await ledger.settleComplete(input.id, 1, { size: stored.size, sha256: await digest(storedBytes),
          profile: "synthetic-bytes-not-audio", etag: stored.etag, version: stored.version })
          .catch(error => { throw new Error(`Completion settlement: ${error.code}`); });
      } else await ledger.cancel(owner, input.id, 1);

      let injectFailure = true;
      const bucket = {
        resumeMultipartUpload: (objectKey, uploadId) => {
          const resumed = this.bucket.resumeMultipartUpload(objectKey, uploadId);
          return { abort: async () => {
            await resumed.abort();
            if (mode === "lost-abort" && injectFailure) { injectFailure = false; throw new Error("simulated lost abort reply"); }
          } };
        },
        delete: async objectKey => {
          await this.bucket.delete(objectKey);
          if (mode === "lost-delete" && injectFailure) { injectFailure = false; throw new Error("simulated lost delete reply"); }
        },
        head: async objectKey => {
          if (mode === "failed-head" && injectFailure) { injectFailure = false; throw new Error("simulated read failure"); }
          return this.bucket.head(objectKey);
        },
      };
      let cleanup = new UploadCleanup(ledger, bucket);
      const first = await cleanup.run();
      if (["lost-abort", "lost-delete", "failed-head"].includes(mode)) {
        check(first.retry === 1 && first.cleaned === 0, "uncertain cleanup retains its task");
        check((await ledger.snapshot(owner, input.id)).state === "cleanup", "quota remains reserved");
        check((await cleanup.run()).attempted === 0, "backoff prevents an immediate retry");
        ledger = new UploadLedger(this.storage, options);
        cleanup = new UploadCleanup(ledger, bucket);
        now += L.retryMs;
        check((await cleanup.run()).cleaned === 1, "cleanup resumes after ledger reconstruction");
      } else check(first.cleaned === 1 && first.retry === 0, "known cleanup succeeded");
      check((await ledger.snapshot(owner, input.id)).state === "cancelled", "cleanup acknowledged");
      check(await this.bucket.head(plan.key) === null, "object is absent");
      let rejected = false;
      try { await upload.uploadPart(1, new Uint8Array([1])); }
      catch (error) { rejected = /\(10024\)$/.test(error.message); }
      check(rejected, "old upload handle cannot accept more bytes");
    }
    const pending = { id: crypto.randomUUID(), room_id: room, occurrence_id: crypto.randomUUID(),
      size: 1, sha256: "a".repeat(64), profile: "mp3-44100-stereo", explicit_selection: true };
    await ledger.admit(owner, pending); await ledger.beginCreate(owner, pending.id, 1);
    await ledger.cancel(owner, pending.id, 1);
    check((await new UploadCleanup(ledger, this.bucket).run()).attempted === 0, "unknown creation is not guessed absent");
    return Response.json({ cases: 6, keys, pending: (await ledger.snapshot(owner, pending.id)).state });
  }
}

export default {
  fetch(request, env) {
    if (new URL(request.url).hostname !== "localhost") return new Response(null, { status: 404 });
    return env.UPLOAD_TEST.get(env.UPLOAD_TEST.newUniqueId()).fetch("http://test/run");
  },
};
